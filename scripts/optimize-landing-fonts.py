"""Rebuild landing font subsets: python -m pip install fonttools brotli.

The original glyphs and metrics are preserved. Disjoint unicode ranges retain
the full original font as an on-demand fallback for future copy and user input.
"""
import json
from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "public/fonts/optimized"
FONTS = [
    ("Pretendard", 400, "Pretendard-Regular.woff2"),
    ("Pretendard", 500, "Pretendard-Medium.woff2"),
    ("Pretendard", 600, "Pretendard-SemiBold.woff2"),
    ("Pretendard", 700, "Pretendard-Bold.woff2"),
    ("Paperlogy", 700, "Paperlogy-7Bold.ttf"),
    ("Paperlogy", 800, "Paperlogy-8ExtraBold.ttf"),
    ("Cafe24Shiningstar", 400, "Cafe24Shiningstar-v2.0.woff2"),
]

def ranges(points):
    groups = []
    for point in sorted(points):
        if groups and point == groups[-1][1] + 1:
            groups[-1][1] = point
        else:
            groups.append([point, point])
    return ",".join(f"U+{a:X}" if a == b else f"U+{a:X}-{b:X}" for a, b in groups)

def face(family, weight, url, points):
    return (f'@font-face {{\n  font-family: "{family}";\n'
            f'  font-weight: {weight};\n  font-style: normal;\n  font-display: swap;\n'
            f'  src: url("{url}") format("woff2");\n'
            f'  unicode-range: {ranges(points)};\n}}\n')

def main():
    characters = set(range(32, 127))
    for directory in ("app", "styles", "lib"):
        for path in (ROOT / directory).rglob("*"):
            if path.suffix in (".tsx", ".ts", ".css") and path.name != "font-subsets.css":
                characters.update(map(ord, path.read_text(encoding="utf-8-sig")))
    OUT.mkdir(parents=True, exist_ok=True)
    css = ["/* Generated by scripts/optimize-landing-fonts.py. Keep full fallback coverage. */\n"]
    report = []
    for family, weight, filename in FONTS:
        source = ROOT / "public/fonts" / filename
        font = TTFont(source)
        original_map = font.getBestCmap()
        all_points = set(original_map)
        core = all_points & characters
        remaining = all_points - core
        original_metrics = {p: font["hmtx"].metrics[original_map[p]] for p in core}
        stem = f"{family}-{weight}"
        fallback_url = f"/fonts/{filename}"
        if source.suffix == ".ttf":
            font.flavor = "woff2"
            font.save(OUT / f"{stem}-full.woff2")
            fallback_url = f"/fonts/optimized/{stem}-full.woff2"
        options = subset.Options()
        options.layout_features = ["*"]
        subsetter = subset.Subsetter(options=options)
        subsetter.populate(unicodes=core)
        subsetter.subset(font)
        font.flavor = "woff2"
        target = OUT / f"{stem}-core.woff2"
        font.save(target)
        check = TTFont(target)
        check_map = check.getBestCmap()
        assert set(check_map) == core, f"Missing glyphs: {filename}"
        assert all(check["hmtx"].metrics[check_map[p]] == original_metrics[p] for p in core)
        assert core.isdisjoint(remaining) and core | remaining == all_points
        css.append(face(family, weight, f"/fonts/optimized/{target.name}", core))
        if remaining:
            css.append(face(family, weight, fallback_url, remaining))
        report.append({"font": filename, "original_bytes": source.stat().st_size,
                       "core_bytes": target.stat().st_size, "core_glyphs": len(core),
                       "fallback_glyphs": len(remaining)})
        print(f"{filename}: {source.stat().st_size:,} -> {target.stat().st_size:,} bytes")
    (ROOT / "styles/font-subsets.css").write_text("\n".join(css), encoding="utf-8")
    (OUT / "report.json").write_text(json.dumps(report, indent=2), encoding="utf-8")

if __name__ == "__main__":
    main()
